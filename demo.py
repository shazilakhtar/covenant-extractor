import pandas as pd
import streamlit as st

from edgar import find_company, search_credit_agreements, fetch_document_html, html_to_text
from chunking import chunk_agreement
from definitions import build_definitions, lookup_definition

st.set_page_config(page_title="Covenant Extractor — demo", layout="wide")
st.title("Covenant Extractor — build so far")
st.caption("Output will be generated by a language model and may be wrong. "
           "It is not legal or financial advice.")


@st.cache_data(show_spinner=False)
def get_filings(ticker):
    company = find_company(ticker)
    if company is None:
        return None, []
    return company, search_credit_agreements(company["cik"])


@st.cache_data(show_spinner=False)
def get_chunks(url):
    text = html_to_text(fetch_document_html(url))
    return text, chunk_agreement(text)


# ---------- Step 1: find the agreements ----------
st.header("1. Find the credit agreements on SEC EDGAR")
ticker = st.text_input("Ticker", value="HAS").strip()
if not ticker:
    st.info("Please enter a ticker.")
    st.stop()

try:
    with st.spinner("Searching EDGAR..."):
        company, filings = get_filings(ticker)
except Exception as e:
    st.error(f"Could not reach SEC EDGAR: {e}")
    st.stop()

if company is None:
    st.warning(f"No company found for ticker {ticker}.")
    st.stop()
if not filings:
    st.warning(f"No credit agreements found for {company['name']}.")
    st.stop()

st.write(f"**{company['name']}**: {len(filings)} credit agreement filings found")
st.dataframe(pd.DataFrame(filings)[["date", "form", "exhibit", "description"]],
             use_container_width=True, hide_index=True)
st.caption("Next step: the model will choose the current agreement from this list "
           "(tool calling). For now we pick the newest.")

choice = st.selectbox("Agreement", range(len(filings)),
                      format_func=lambda i: f'{filings[i]["date"]} — {filings[i]["description"][:80]}')
doc = filings[choice]

# ---------- Step 2: download and chunk ----------
st.header("2. Download and cut into sections")
try:
    with st.spinner("Downloading and chunking..."):
        text, chunks = get_chunks(doc["url"])
except Exception as e:
    st.error(f"Could not download the agreement: {e}")
    st.stop()

definitions = build_definitions(chunks)
c1, c2, c3 = st.columns(3)
c1.metric("Characters", f"{len(text):,}")
c2.metric("Chunks (by section)", len(chunks))
c3.metric("Defined terms", len(definitions))

# ---------- Step 3: the covenant section ----------
st.header("3. The financial covenant section")
st.caption("Found here by a simple title match. Next step: embeddings + retrieval (Adwoa).")
cov = [c for c in chunks if "financial covenant" in c["title"].lower()]
if not cov:
    st.warning("No section titled 'Financial Covenants' found. Could be cov-lite, "
               "or the covenant sits under another title. Retrieval will handle this.")
for c in cov:
    with st.expander(f'Section {c["section"]} — {c["title"]}', expanded=True):
        st.text(c["text"][:3000])

# ---------- Step 4: definitions lookup (the model's tool) ----------
st.header("4. Definitions lookup — the tool the model will call")
if definitions:
    terms = sorted(definitions)
    default = next((i for i, t in enumerate(terms) if "Leverage Ratio" in t), 0)
    term = st.selectbox("Defined term", terms, index=default)
    result = lookup_definition(term, definitions)
    st.write(result["definition"])
    if result["uses_terms"]:
        st.write("**This definition depends on:** " + ", ".join(result["uses_terms"]))

# ---------- Step 5: target output ----------
st.header("5. Target output (not generated yet)")
st.caption("What the finished app will return. Hand-coded for Hasbro to show the goal; "
           "the model is not connected yet.")
if ticker.upper() == "HAS":
    st.dataframe(pd.DataFrame([
        {"Covenant": "Consolidated Net Total Leverage Ratio", "Type": "Maximum",
         "Level": "3.75x (4.00x for Sep 30 quarter)", "First test": "Mar 31, 2026",
         "Section": "7.05(b)"},
        {"Covenant": "Consolidated Interest Coverage Ratio", "Type": "Minimum",
         "Level": "3.00x", "First test": "Mar 31, 2026", "Section": "7.05(a)"},
    ]), use_container_width=True, hide_index=True)
else:
    st.info("Target table shown for HAS only.")
