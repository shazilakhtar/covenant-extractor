import pandas as pd
import streamlit as st

from headroom import calculate_headroom

MAX_REQUESTS = 10  # guardrail: searches allowed per session

st.set_page_config(page_title="Covenant Extractor")
st.title("Covenant Extractor")
st.write("Enter a company ticker. The app finds its credit agreement on SEC EDGAR and "
         "pulls out the financial covenants, with the section each one comes from.")
st.warning("Output is generated by a language model and may be wrong. "
           "It is not legal or financial advice.")

if "request_count" not in st.session_state:
    st.session_state["request_count"] = 0


# --- Shazil: cached steps, so the same ticker or agreement never costs quota twice ---
@st.cache_data(show_spinner=False, ttl=24 * 3600)
def cached_filings(ticker):
    from edgar import find_company, search_credit_agreements
    company = find_company(ticker)
    if company is None:
        return None, []
    return company, search_credit_agreements(company["cik"])


@st.cache_resource(show_spinner=False)
def cached_document(url):
    from pipeline import load_document
    return load_document(url)


class TemporaryFailure(Exception):
    """Raised so a failed model call is NOT cached and the user can simply retry."""
    def __init__(self, result):
        super().__init__(result.get("error"))
        self.result = result


@st.cache_data(show_spinner=False)
def cached_extraction(url, prompt_version):
    from extractor import extract_covenants
    chunks, ops_chunks, vectors, definitions = cached_document(url)
    result = extract_covenants(ops_chunks, vectors, definitions)
    if result["status"] == "api_error":
        raise TemporaryFailure(result)   # do not remember failures
    return result


def run_search(ticker, choice=None):
    """Find the filings, pick the agreement, extract. Stores everything in session_state."""
    from pipeline import pick_agreement
    from prompts import EXTRACT_PROMPT_VERSION
    company, filings = cached_filings(ticker)
    if company is None:
        st.session_state["error"] = f"No company found for ticker {ticker}."
        return
    if not filings:
        st.session_state["error"] = f"No credit agreements found on EDGAR for {company['name'].rstrip('.')}."
        return
    idx = pick_agreement(filings) if choice is None else choice
    url = filings[idx]["url"]
    with st.spinner("Reading the agreement. The first time for a new agreement takes "
                    "about 2 minutes (free-tier limits); after that it is instant."):
        try:
            result = cached_extraction(url, EXTRACT_PROMPT_VERSION)
        except TemporaryFailure as e:
            result = e.result
    st.session_state.update(company=company, filings=filings, choice=idx,
                            result=result, error=None, error_detail=None)


# ---------------- Search ----------------
tab_main, tab_how = st.tabs(["Covenants", "How it works"])

with tab_main:
    ticker = st.text_input("Ticker", placeholder="e.g. HAS").strip().upper()
    if st.button("Find covenants", type="primary"):
        if not ticker:
            st.info("Please enter a ticker.")
        elif st.session_state["request_count"] >= MAX_REQUESTS:
            st.warning(f"You have reached the limit of {MAX_REQUESTS} searches for this "
                       "session. Please refresh the page to start a new session.")
        else:
            st.session_state["request_count"] += 1
            try:
                run_search(ticker)
            except Exception as e:
                st.session_state["error"] = ("Could not reach SEC EDGAR or Gemini right now. "
                                             "Please try again in a minute.")
                st.session_state["error_detail"] = str(e)
    st.caption(f"Searches remaining this session: "
               f"{MAX_REQUESTS - st.session_state['request_count']}")

    if st.session_state.get("error"):
        st.error(st.session_state["error"])
        if st.session_state.get("error_detail"):
            with st.expander("Technical details"):
                st.code(st.session_state["error_detail"])

    result = st.session_state.get("result")
    if result and not st.session_state.get("error"):
        filings, idx = st.session_state["filings"], st.session_state["choice"]
        f = filings[idx]
        st.subheader(st.session_state["company"]["name"])
        st.write(f"**Agreement used:** {f['description'][:100]} (filed {f['date']}) "
                 f"[open on EDGAR]({f['url']})")

        # --- Shazil: show the model's result, or a clear message when it failed ---
        if result["status"] == "api_error" and "per day" in result.get("error", "").lower():
            st.error("The app has used its free daily allowance of model requests. "
                     "It resets at midnight Pacific time. Please try again tomorrow.")
            with st.expander("Technical details"):
                st.code(result.get("error", ""))
        elif result["status"] == "api_error":
            st.error("The language model could not be reached (it may be busy). "
                     "Please try again in a minute.")
            with st.expander("Technical details"):
                st.code(result.get("error", ""))
        elif result["status"] == "parse_error":
            st.error("The model's answer could not be read, so no table is shown "
                     "rather than a possibly wrong one. " + result.get("error", ""))
        else:
            data = result["data"]
            if data.get("covenant_lite") or not data["covenants"]:
                st.info("No financial maintenance covenant found in this agreement "
                        "(it may be covenant-lite).")
            else:
                rows = [{
                    "Covenant": c.get("name"),
                    "Type": (c.get("kind") or "").capitalize(),
                    "Level": f'{c["level"]:.2f}x' if c["level_is_number"] else str(c.get("level")),
                    "First test date": c.get("first_test_date") or "—",
                    "Section": c.get("section"),
                    "Quote checked": "✓" if c["quote_found"] else "✗ not found in text",
                } for c in data["covenants"]]
                st.dataframe(pd.DataFrame(rows), hide_index=True, use_container_width=True)
                for c in data["covenants"]:
                    with st.expander(f'Section {c.get("section")} — {c.get("name")}'):
                        st.markdown(f'> {c.get("supporting_quote")}')
                        if c.get("schedule"):
                            st.write("**Schedule:**", c["schedule"])
                        if c.get("condition"):
                            st.write("**Applies only when:**", c["condition"])

        with st.expander("Use a different agreement"):
            new = st.selectbox("Filing", range(len(filings)), index=idx,
                               format_func=lambda i: f'{filings[i]["date"]} — '
                                                     f'{filings[i]["description"][:80]}')
            if st.button("Read this one") and new != idx:
                if st.session_state["request_count"] >= MAX_REQUESTS:
                    st.warning("Search limit reached for this session.")
                else:
                    st.session_state["request_count"] += 1
                    try:
                        run_search(ticker or st.session_state["company"]["name"], new)
                        st.rerun()
                    except Exception:
                        st.error("Could not read that agreement. Please try again.")

    # ---------------- Headroom (Norbesida) ----------------
    st.divider()
    st.subheader("Headroom (optional)")
    st.write("How far is the company from breaking its maximum leverage covenant?")

    default_limit = 3.75
    if result and result.get("status") == "ok":   # Shazil: prefill with the extracted limit
        lev = [c for c in result["data"]["covenants"]
               if c.get("metric") == "leverage" and c.get("level_is_number")]
        if lev:
            default_limit = float(lev[0]["level"])

    debt = st.number_input("Debt ($M)", min_value=0.0, value=750.0, step=10.0)
    ebitda = st.number_input("EBITDA ($M)", min_value=0.0, value=250.0, step=10.0)
    limit = st.number_input("Leverage limit (x)", min_value=0.0, value=default_limit, step=0.25)

    if st.button("Calculate headroom"):
        try:
            h = calculate_headroom("maximum", limit, debt, ebitda)
            if "error" in h:
                st.error(h["error"])
            else:
                col1, col2, col3 = st.columns(3)
                col1.metric("Actual leverage", f"{h['actual_ratio']}x")
                col2.metric("Headroom", f"{h['headroom_pct']}%")
                col3.metric("EBITDA cushion", f"{h['ebitda_cushion_pct']}%")
                if h["in_compliance"]:
                    st.success("In compliance with the covenant.")
                else:
                    st.error("In breach of the covenant.")
        except Exception:
            st.error("Something went wrong with the calculation. Please check your numbers.")

# ---------------- How it works (Shazil) ----------------
with tab_how:
    result = st.session_state.get("result")
    if not result:
        st.write("Run a search first. This tab then shows what the app sent to the model.")
    else:
        st.write(f'**Model:** {result["model"]}  ·  **Prompt version:** {result["prompt_version"]}')
        st.write(f'**Tokens:** {result["tokens_in"]:,} in / {result["tokens_out"]:,} out')
        st.write("**Definitions the model looked up (tool calls):** "
                 + (", ".join(result["tool_calls"]) or "none"))
        st.write("**Sections retrieved and sent to the model:**")
        st.dataframe(pd.DataFrame(result.get("retrieved", []),
                                  columns=["Section", "Title", "Similarity"]),
                     hide_index=True, use_container_width=True)
        with st.expander("Raw model answer"):
            st.code(result.get("raw") or "", language="json")
