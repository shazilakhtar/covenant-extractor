
import pandas as pd
import streamlit as st
 
from headroom import calculate_headroom  # my function from headroom.py
 
MAX_REQUESTS = 10  # guardrail: button presses allowed per session
 
 
# ---------------------------------------------------------------
# Fake results (placeholder until the model is connected)
# ---------------------------------------------------------------
def get_fake_results(ticker):
    """Returns a table of FAKE covenants. Later this will call Gemini."""
    rows = [
        {
            "Covenant": "Net Total Leverage",
            "Type": "Maximum",
            "Level": "3.75x",
            "First test date": "Placeholder",
            "Section": "7.05",
            "Supporting text": "[Placeholder] Leverage may not exceed 3.75 to 1.00.",
        },
        {
            "Covenant": "Interest Coverage",
            "Type": "Minimum",
            "Level": "3.00x",
            "First test date": "Placeholder",
            "Section": "7.05",
            "Supporting text": "[Placeholder] Coverage may not be below 3.00 to 1.00.",
        },
    ]
    return pd.DataFrame(rows)
 
 
# ---------------------------------------------------------------
# Page setup: title, description, always-visible disclaimer
# ---------------------------------------------------------------
st.set_page_config(page_title="Covenant Extractor")
 
st.title("Covenant Extractor")
st.write("Enter a company ticker to find the financial covenants in its loan agreement.")
 
# Not inside any button or if-statement, so it is always on screen
st.warning(
    "Output is generated by a language model and may be wrong. "
    "It is not legal or financial advice."
)
 
# ---------------------------------------------------------------
# Memory across reruns: Streamlit re-runs this whole file on every click,
# so anything we want to keep goes in st.session_state.
# ---------------------------------------------------------------
if "request_count" not in st.session_state:
    st.session_state["request_count"] = 0
if "results" not in st.session_state:
    st.session_state["results"] = None
 
# ---------------------------------------------------------------
# Ticker input and "Find covenants" button
# ---------------------------------------------------------------
ticker = st.text_input("Ticker", placeholder="e.g. HAS")
find_clicked = st.button("Find covenants")
 
if find_clicked:
    try:
        clean_ticker = ticker.strip().upper()  # remove spaces, make capitals
 
        if clean_ticker == "":
            # Guardrail: empty input -> friendly message (not counted as a request)
            st.info("Please enter a ticker.")
 
        elif st.session_state["request_count"] >= MAX_REQUESTS:
            # Guardrail: request limit reached -> polite message, no work done
            st.warning(
                f"You have reached the limit of {MAX_REQUESTS} searches for this "
                "session. Please refresh the page to start a new session."
            )
 
        else:
            st.session_state["request_count"] += 1  # count this press
            st.session_state["results"] = get_fake_results(clean_ticker)
 
    except Exception:
        # Guardrail: friendly message instead of a red traceback
        st.error("Something went wrong while finding covenants. Please try again.")
 
# Show how many searches are left
remaining = MAX_REQUESTS - st.session_state["request_count"]
st.caption(f"Searches remaining this session: {remaining}")
 
# ---------------------------------------------------------------
# Results table (shown whenever we have saved results)
# ---------------------------------------------------------------
if st.session_state["results"] is not None:
    st.subheader("Covenants found")
    st.caption("Demo data: these results are fake until the model is connected.")
    st.dataframe(st.session_state["results"], hide_index=True)
 
# ---------------------------------------------------------------
# Optional headroom section
# ---------------------------------------------------------------
st.divider()
st.subheader("Headroom (optional)")
st.write("How far is the company from breaking a maximum leverage covenant?")
 
debt = st.number_input("Debt ($M)", min_value=0.0, value=750.0, step=10.0)
ebitda = st.number_input("EBITDA ($M)", min_value=0.0, value=250.0, step=10.0)
limit = st.number_input("Leverage limit (x)", min_value=0.0, value=3.75, step=0.25)
 
if st.button("Calculate headroom"):
    try:
        # Leverage is a "maximum" covenant: numerator = debt, denominator = EBITDA
        result = calculate_headroom("maximum", limit, debt, ebitda)
 
        if "error" in result:
            # The function returned a clear error message, so we show it
            st.error(result["error"])
        else:
            col1, col2, col3 = st.columns(3)
            col1.metric("Actual leverage", f"{result['actual_ratio']}x")
            col2.metric("Headroom", f"{result['headroom_pct']}%")
            col3.metric("EBITDA cushion", f"{result['ebitda_cushion_pct']}%")
 
            if result["in_compliance"]:
                st.success("In compliance with the covenant.")
            else:
                st.error("In breach of the covenant.")
 
    except Exception:
        st.error("Something went wrong with the calculation. Please check your numbers.")
 
